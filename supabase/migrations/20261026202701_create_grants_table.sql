CREATE TABLE public.grants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    title TEXT NOT NULL,
    granting_agency TEXT NOT NULL,
    program TEXT,
    years_awarded TEXT,
    role TEXT,
    collaborators TEXT[],
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Enable Row Level Security (RLS)
ALTER TABLE public.grants ENABLE ROW LEVEL SECURITY;

-- Create policies so users can only manage their own grants
CREATE POLICY "Users can view their own grants"
    ON public.grants FOR SELECT
    USING (auth.uid() = user_id);

CREATE POLICY "Users can insert their own grants"
    ON public.grants FOR INSERT
    WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can update their own grants"
    ON public.grants FOR UPDATE
    USING (auth.uid() = user_id);

CREATE POLICY "Users can delete their own grants"
    ON public.grants FOR DELETE
    USING (auth.uid() = user_id);